# 使い方:
#   export YOKUMAKUN_SUDO_PASS='...'
#   bash bootstrap_tunnel_embedded.sh
set -euo pipefail
ROOT="${YOKUMAKUN_ROOT:-/opt/yokuumakun_auto-x}"
SUDO_PASS="${YOKUMAKUN_SUDO_PASS:-${YOKUMAKUN_SSH_PASS:-}}"
TMP="$(mktemp -d)"
cleanup() { rm -rf "$TMP"; }
trap cleanup EXIT

sudo_run() {
  if [[ -n "$SUDO_PASS" ]]; then
    echo "$SUDO_PASS" | sudo -S -p '' "$@"
  else
    sudo "$@"
  fi
}

echo "INFO: embedded SSH tunnel bootstrap root=$ROOT"
if [[ ! -d "$ROOT" ]]; then
  echo "ERROR: missing $ROOT" >&2
  exit 2
fi
mkdir -p "$ROOT/server_deployment" "$ROOT/logs" "$ROOT/.local/bin"

b64decode() {
  if command -v base64 >/dev/null 2>&1; then
    base64 -d 2>/dev/null || base64 --decode
  else
    python3 -c 'import sys,base64; sys.stdout.buffer.write(base64.b64decode(sys.stdin.read()))'
  fi
}

